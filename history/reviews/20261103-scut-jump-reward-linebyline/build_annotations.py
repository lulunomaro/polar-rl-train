def mapping(text):
    out = {}
    for row in text.strip().splitlines():
        span, note = row.split('|', 1)
        parts = span.strip().split('-')
        first, last = int(parts[0]), int(parts[-1])
        for n in range(first, last+1):
            out[n] = note.strip()
    return out

def source_ref(path):
    raw = path.read_bytes()
    row = {'path': str(path), 'bytes': len(raw), 'sha256': hashlib.sha256(raw).hexdigest(),
           'git_blob': hashlib.sha1(b'blob '+str(len(raw)).encode()+b'\0'+raw).hexdigest()}
    if path.is_relative_to(PRIMARY):
        upstream = path.relative_to(PRIMARY).as_posix()
        row['upstream_path'] = upstream
        row['existing_git_path'] = 'versions/20261101_mod4-human10mm-depth-stair-supermimic-admission246/SCUT_UPSTREAM_JUMP_STAIRS_REWARD_REVIEW_V245_20261101/primary/'+upstream
    elif path.is_relative_to(REPO):
        row['existing_git_path'] = path.relative_to(REPO).as_posix()
    if row not in INDEX['files']:
        INDEX['files'].append(row)
    return row

def annotate(path, first, last, notes, label):
    ref = source_ref(path)
    lines = path.read_text(encoding='utf8').splitlines()
    out = [f'\n### {label}\n', f'原文件 `{ref.get("upstream_path", ref.get("existing_git_path"))}`，L{first}–L{last}。注释中的行号对应本地原始字节，不使用网页渲染时压缩空行的行号。\n', '```python' if path.suffix == '.py' else '```yaml']
    covered, code_count = [], 0
    for n in range(first, last+1):
        raw = lines[n-1]
        stripped = raw.strip()
        if not stripped:
            out.append('')
            continue
        if stripped.startswith('#'):
            out.append(raw + f'  [原L{n}：原作者注释，不执行]')
            continue
        code_count += 1
        note = notes.get(n)
        if note is None:
            if re.fullmatch(r'[\)\]\},]+', stripped):
                note = '闭合上面的跨行表达式；不另产生奖励。'
            else:
                raise ValueError(f'Missing semantic annotation: {path.name}:{n}: {raw}')
        covered.append(n)
        out.append(raw + f'  # 原L{n}：{note}')
    out.append('```\n')
    INDEX['coverage'].append({'output': label, 'source': str(path), 'start': first, 'end': last,
                              'nonblank_noncomment_lines': code_count, 'annotated': len(covered)})
    return '\n'.join(out)

def write(name, intro, blocks):
    (HERE/name).write_text(intro+'\n'+''.join(blocks), encoding='utf8')

