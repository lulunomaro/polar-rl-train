#!/usr/bin/env python3
"""Generate a small C header that normalizes H7 raw drive units to RL units."""
from __future__ import annotations

import argparse
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def main() -> int:
  ap = argparse.ArgumentParser()
  ap.add_argument("--calibration", required=True)
  ap.add_argument("--contract", default=str(ROOT / "train/deploy/contract.json"))
  ap.add_argument("--out", required=True)
  args = ap.parse_args()
  subprocess.run([sys.executable, str(ROOT / "scripts/check_hardware_calibration.py"),
                  "--contract", args.contract, "--calibration", args.calibration], check=True)
  cal = json.loads(Path(args.calibration).read_text(encoding="utf-8"))
  rows = cal["joints"]

  def array(key: str) -> str:
    return ", ".join(f"{float(row[key]):.17g}" for row in rows)

  names = ", ".join('"' + row["name"] + '"' for row in rows)
  text = f"""// Generated by scripts/generate_h7_joint_contract.py. Do not hand edit.
#pragma once
#include <stddef.h>

static const size_t RM_JOINT_COUNT = {len(rows)};
static const char* const RM_JOINT_NAMES[{len(rows)}] = {{{names}}};
static const double RM_RAW_ZERO[{len(rows)}] = {{{array('raw_zero')}}};
static const double RM_SIGN[{len(rows)}] = {{{array('sign')}}};
static const double RM_POS_UNITS_PER_MODEL_RAD[{len(rows)}] = {{{array('raw_position_units_per_model_rad')}}};
static const double RM_EFFORT_UNITS_PER_MODEL_NM[{len(rows)}] = {{{array('raw_effort_units_per_model_nm')}}};

static inline double rm_model_position(size_t i, double raw) {{
  return RM_SIGN[i] * (raw - RM_RAW_ZERO[i]) / RM_POS_UNITS_PER_MODEL_RAD[i];
}}
static inline double rm_model_velocity(size_t i, double raw) {{
  return RM_SIGN[i] * raw / RM_POS_UNITS_PER_MODEL_RAD[i];
}}
static inline double rm_model_effort(size_t i, double raw) {{
  return RM_SIGN[i] * raw / RM_EFFORT_UNITS_PER_MODEL_NM[i];
}}
static inline double rm_raw_position(size_t i, double model) {{
  return RM_RAW_ZERO[i] + RM_SIGN[i] * model * RM_POS_UNITS_PER_MODEL_RAD[i];
}}
static inline double rm_raw_velocity(size_t i, double model) {{
  return RM_SIGN[i] * model * RM_POS_UNITS_PER_MODEL_RAD[i];
}}
static inline double rm_raw_effort(size_t i, double model) {{
  return RM_SIGN[i] * model * RM_EFFORT_UNITS_PER_MODEL_NM[i];
}}
// If the drive closes PD directly in raw coordinates, transform output-space
// Kp/Kd by effort_units/position_units.  With a raw rotor coordinate this is
// the familiar 1/reduction^2 gain conversion.
static inline double rm_raw_pd_gain(size_t i, double model_gain) {{
  return model_gain * RM_EFFORT_UNITS_PER_MODEL_NM[i] /
         RM_POS_UNITS_PER_MODEL_RAD[i];
}}
"""
  out = Path(args.out)
  out.parent.mkdir(parents=True, exist_ok=True)
  out.write_text(text, encoding="utf-8", newline="\n")
  print("wrote", out)
  return 0


if __name__ == "__main__":
  sys.exit(main())
